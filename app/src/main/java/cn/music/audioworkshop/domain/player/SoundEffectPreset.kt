package cn.music.audioworkshop.domain.player

/**
 * 播放音效预设。
 *
 * 建模思路照 lx-music-desktop 的音效链：
 *
 * ```
 * source → EQ → 干路(mainGain) ─────────────┐
 *                            空间感 → 湿路(sendGain) ─┴→ 限幅 → 输出
 * ```
 *
 * lx 那边混响靠 15 个真实 IR wav；这里按声学参数实时合成
 * （[cn.music.audioworkshop.media.reverb.ReverbEngine]），素材不落地、没有授权问题。
 *
 * RT-60 取自常见声学参考值：小房间 0.3–0.6s，音乐厅 1.8–2.2s，教堂 4–8s。
 *
 * 五个预设的差异要能在耳朵里分辨，靠的是**三个维度一起拉开**，只改一个不够：
 *
 * | 预设 | 尾音 | 阻尼（高频） | 尺度 | 特征 |
 * |---|---|---|---|---|
 * | 室内 | 短 | 中 | 小 | 中性参照，日常听感 |
 * | 电影院 | 中长 | **很闷** | 大 | 厚地毯座椅，高频先死 |
 * | 大厅 | 长 | **很亮** | 大 | 硬质墙面，尾音透亮 |
 * | 教堂 | **极长** | 亮 | 最大 | 石壁，尾巴拖到散掉 |
 * | 磁性立体声 | 几乎无 | 不衰减 | — | 声场缓慢环绕，不是房间 |
 *
 * **电影院 vs 大厅是最容易混的一对**，特意做成「同样长、一个闷一个亮」，
 * 避免只靠尾音长短区分。
 *
 * **磁性立体声不是房间。** 它对应 lx 的 [AudioPanner]（声像旋转），
 * 尾音几乎为零，靠 [rotating] 让声场缓慢环绕 —— 这是它和前四个的
 * 本质区别，也是一耳朵能听出来的。
 */
enum class SoundEffectPreset(
    val displayName: String,
    val description: String,
    /**
     * 混响衰减 60dB 所需秒数。0 表示关闭。
     */
    val rt60Seconds: Float,
    /** 高频阻尼 0..1，越大越闷。 */
    val damping: Float,
    /** 湿声比例 0..1，也就是 lx 那边的 sendGain。 */
    val wet: Float,
    /** 预延迟毫秒。直达声到第一个反射的间隔，小空间几乎为 0。 */
    val preDelayMs: Float,
    /** 立体声展宽 0..1，小空间很窄，场馆最宽。 */
    val stereoWidth: Float,
    /**
     * 房间尺度 0..1。决定**早期反射的间隔**和 FDN 延迟线长度。
     * 尾巴长度由 [rt60Seconds] 管，尺度由这个管，两者不能混：
     * 空旷的户外空间尾巴长但反射稀疏，卫生间正好相反。
     */
    val roomSize: Float,
    /** 是否走听筒窄带。电话用，其余都不是 —— 它不是房间，是带宽限制。 */
    val telephoneBand: Boolean = false,
    /** 软削波量 0..1，给电话一点沙哑感。 */
    val drive: Float = 0f,
    /** 是否让声像缓慢环绕（lx 的 panner）。不是混响，是空间定位。 */
    val rotating: Boolean = false,
) {
    NONE("无", "原声", 0f, 0f, 0f, 0f, 0f, 0f),

    // ---- 小空间：尾音短、很干 ----

    /** 瓷砖全反射，RT60 约 0.5s，高频几乎不衰减（瓷砖不吸高频）。 */
    BATHROOM("卫生间", "瓷砖小空间，混响短促", 0.50f, 0.12f, 0.34f, 8f, 0.30f, 0.18f),
    /** 普通居室 / 办公室。短、平衡、中性，当参照系用。 */
    INDOOR("室内", "普通房间，中性短混响", 0.55f, 0.40f, 0.24f, 10f, 0.45f, 0.30f),
    /** 满座 + 餐具 + 桌布，人和家具吸收很多，RT60 约 0.75s。对应 lx 的 medium-room。 */
    RESTAURANT("餐厅", "嘈杂中等混响", 0.75f, 0.45f, 0.30f, 14f, 0.55f, 0.42f),

    // ---- 大空间：按「明亮 / 沉闷」两极拉开 ----

    /**
     * 厚地毯 + 软座吸掉高频，RT60 约 1.1s 但很闷。
     * 对应 lx 的 `cinema-diningroom.wav`。
     */
    CINEMA("电影院", "厚地毯座椅，尾音长但很闷", 1.10f, 0.72f, 0.26f, 26f, 0.70f, 0.80f),

    /**
     * 演唱会现场。
     *
     * **满场观众是最强的吸声体** —— 几千个人体吸收高频，所以真演唱会的
     * 尾音比空大厅短、也闷。这一点是它和其余房间的判别依据：
     * 卡在电影院（更闷）和大厅（更亮）中间，**但宽度全场最高**（0.92），
     * 因为声源来自四面八方的舞台返听和人群，不是单点。
     */
    CONCERT("演唱会", "满场观众吸声，包裹感强", 1.40f, 0.45f, 0.32f, 18f, 0.92f, 0.85f),

    /**
     * 音乐厅硬质反射面，RT60 约 2.0s，所以明亮透亮。
     * 对应 lx 的 `bright-hall.wav`。
     */
    HALL("大厅", "宽敞明亮，尾音长且透亮", 2.00f, 0.20f, 0.36f, 30f, 0.85f, 0.88f),

    /**
     * 石壁教堂。RT60 取 4.5s（常见范围 4–8s 的偏低段，再长就只是拖）。
     * 教堂是四个房间里最难和「大厅」区分的，所以往两个方向同时拉：
     * **尾巴拉长到大厅的两倍多，同时高频完全不衰减**（石头不吸高频）。
     */
    CATHEDRAL("教堂", "石壁超长混响，尾音透亮", 4.50f, 0.10f, 0.42f, 45f, 0.80f, 1.00f),

    // ---- 以下两个不是房间 ----

    /**
     * 听筒。**不是房间，是带宽限制。**
     *
     * 把 300–3400Hz 以外滤掉（当年 GSM 编码器的带宽），再压一点混响，
     * 配一点软削波制造沙哑的谐波感。混响参数几乎不起作用。
     */
    TELEPHONE("电话", "听筒窄带，沙哑", 0.15f, 0.10f, 0.06f, 0f, 0.10f, 0.02f, telephoneBand = true, drive = 0.35f),

    /**
     * 磁性立体声。**也不是房间。**
     *
     * 对应 lx 的 [AudioPanner] + `tim-omni-35-10-magnetic.wav`：
     * 全指向扬声器的空间渲染 + 声像缓慢环绕。混响几乎为零（RT60 0.28s
     * 只是为了让声音「离耳远一点」），真正起作用的是 [rotating] ——
     * 声场每 12 秒绕一圈，听起来像声音在四周转。
     *
     * 阻尼给 0：不衰减高频，保持通透，否则转起来会闷。
     */
    MAGNETIC("磁性立体声", "声场缓慢环绕，不是房间", 0.28f, 0f, 0.14f, 6f, 1.00f, 0.50f, rotating = true),
    ;

    val isEnabled: Boolean get() = rt60Seconds > 0f

    companion object {
        /** 预设页按这个顺序展示：先是参照系，再按空间从小到大。 */
        val selectable: List<SoundEffectPreset> = entries.toList()

        /** 按名字取，取不到当「无」。服务重启、进程被杀后回读设置用。 */
        fun fromName(name: String?): SoundEffectPreset =
            entries.firstOrNull { it.name == name } ?: NONE
    }
}
