package cn.qishui.tool.feature.effect

/**
 * 每个功能的温馨提示。文案按我们实际接入的算法写，
 * 和参考图里说的实现不一致的地方以我们为准。
 */
fun effectHint(id: String): String = when (id) {
    "reverse" -> "倒放会把音频完全反向播放。" +
        "变速和降噪类处理都会先解码再编码，导出为 MP3 会产生一次有损编码。"

    "invert" -> "反转相位会把波形上下颠倒，播放时听感更闷、音量感觉变小，但音频数据本身没有损失。"

    "echo" -> "回声效果通过延迟叠加实现。延迟越短越容易产生梳状滤波（听起来像手机外放），" +
        "建议 80ms 以上；反馈拉高会明显增加音量，超过 0.7 容易糊。"

    "choir" -> "合唱效果用几路不同延时的干声叠加制造厚度，不改变音高，" +
        "所以不会像变速那样影响清晰度。"

    "reverb" -> "我们用的是 Schroeder 结构（4 组梳状滤波 + 2 组全通），" +
        "空间调大后尾音更长、CPU 占用也更高。"

    "equalizer" -> "三段均衡：低频 250Hz 以下、中频 250Hz~4kHz、高频 4kHz 以上。" +
        "我们用低通/高通分频后叠加增益实现，比架式滤波器更不容易在低频失真。"

    "stereo_split" -> "立体声分离靠中置消除：只保留左右声道差（去人声）或只保留中置（保留人声）。" +
        "单声道文件或相位抵消严重的录音效果会不明显。"

    "stereo_widen" -> "立体声环绕用 M/S 矩阵拉宽声场，宽度拉满会明显偏离原音色。"

    "stereo_mix" -> "立体声合成按比例混合左右声道，声像偏向一侧会削弱另一侧的能量。"

    "silence_trim" -> "去除头尾按阈值找出首尾有声位置，阈值越高判定为静音的区间越大。" +
        "录白噪底的现场录音建议阈值不要超过 -40dB。"

    "radio_fx" -> "收音机音效是 300Hz~3.4kHz 带通加轻微削波，用来模拟老式收音机的窄频响。"

    "repair" -> "音频修复做两件事：去直流偏移、把削波点用前后样本插值抹平。" +
        "它能修明显失真，但修不了已经丢失的信息。"

    "convert" -> "格式转换会统一采样率和声道数。当前 LAME 编码器只支持 44100Hz 和 48000Hz，" +
        "所以目标采样率只有这两个可选。"

    "mix" -> "混音把多首歌的波形逐样本相加，超过满幅会自动限幅，" +
        "所以增益总和别超过 0dB，否则会削顶。"

    "denoise" -> "降噪用的是 RNNoise（Xiph 官方，Firefox 和 WebRTC 同款神经网络算法），" +
        "针对平稳背景噪声（风扇、电流声）效果最好，对人声和音乐本身会有些损失。" +
        "它固定工作在 48000Hz，我们会自动重采样。"

    "speed_pitch" -> "变速变调用的是 Signalsmith Stretch（BBC R&D 在 ADC22 发表的算法，MIT 许可），" +
        "变速和变调同时完成、互不影响，并且会尽量保住音色。" +
        "速度和时间是反比关系：速度 2.0x 出来的一半长。" +
        "我们没有做变速内核切换，Signalsmith 在 0.25x~4x 之间都能正常工作。"

    "segment_pitch" -> "分段变调只对生效区间内的音频做移调，区间外原样保留。" +
        "留空区间表示处理整首。"

    "segment_gain" -> "分段修改音量只对生效区间内的音频加增益，区间外原样保留。" +
        "留空区间表示处理整首。"

    "loudness" -> "响度标准化按 EBU R128 / ITU BS.1770 标准测量整体响度（LUFS）并调整到目标值。" +
        "这是 Spotify、YouTube 用的标准，比单纯把峰值顶满更接近听感一致。" +
        "默认 -14 LUFS 是流媒体常用值。"

    else -> "处理完成后导出为 MP3。"
}
