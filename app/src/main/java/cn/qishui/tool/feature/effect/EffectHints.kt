package cn.qishui.tool.feature.effect

/**
 * 每个功能的温馨提示。文案按我们实际接入的算法写，
 * 和参考图里说的实现不一致的地方以我们为准。
 */
fun effectHint(id: String): String = when (id) {
    "reverse" -> "倒放会把音频完全反向播放。" +
        "变速和降噪类处理都会先解码再编码，导出为 MP3 会产生一次有损编码。"

    "invert" -> "反转相位会把波形上下颠倒，播放时听感更闷、音量感觉变小，但音频数据本身没有损失。"

    "echo" -> "回声效果通过延迟叠加实现。延迟越短越容易产生梳状滤波（听起来像手机外放），" +
        "建议 80ms 以上；反馈拉高会明显增加音量，超过 0.7 容易糊。"

    "choir" -> "合唱效果用几路不同延时的干声叠加制造厚度，不改变音高，" +
        "所以不会像变速那样影响清晰度。"

    "reverb" -> "我们用的是 Schroeder 结构（4 组梳状滤波 + 2 组全通），" +
        "空间调大后尾音更长、CPU 占用也更高。"

    "equalizer" -> "三段均衡：低频 250Hz 以下、中频 250Hz~4kHz、高频 4kHz 以上。" +
        "我们用低通/高通分频后叠加增益实现，比架式滤波器更不容易在低频失真。"

    "stereo_split" -> "立体声分离靠中置消除：只保留左右声道差（去人声）或只保留中置（保留人声）。" +
        "单声道文件或相位抵消严重的录音效果会不明显。"

    "stereo_widen" -> "立体声环绕用 M/S 矩阵拉宽声场，宽度拉满会明显偏离原音色。"

    "stereo_mix" -> "立体声合成把两首歌分别放进左右声道，戴耳机才听得出差别。" +
        "两首采样率不一致时会自动统一到较高的那个。"

    "silence_trim" -> "去除头尾按你填的毫秒数直接砍掉，不做静音检测。" +
        "头尾砍完可能比原曲短很多，导出前建议先试听一下剩下的部分。"

    "mix" -> "混音是按你选择的顺序把几首歌首尾拼起来，交界处做淡入淡出。" +
        "淡入淡出时间越长，两首歌重叠的部分越多，总时长也越短。" +
        "开启格式化音乐会先把所有歌曲统一到最高的采样率，避免拼完变速。"

    "radio_fx" -> "收音机音效是带通滤波（收窄频响）加削波失真和可选底噪，用来模拟老式收音机。" +
        "模式决定频响宽度：稳定最接近原声，破音最夸张。" +
        "导出建议用 WAV：这种效果本身加了失真，再过一道有损编码会更容易发糊。"

    "repair" -> "音频修复做两件事：把削波点用前后样本插值抹平、去掉直流偏移。" +
        "修复强度分轻度 / 标准 / 强力三档，强度越高被处理的范围越大。" +
        "处理顺序是「先修削波再去直流」——反过来会让顶在满幅的采样被压到判定阈值以下，" +
        "反而认不出哪些点是削波的了。" +
        "它能修明显的失真，但修不了已经丢失的信息。"

    "segment_pitch" -> "分段变调只对片段区间内的音频移调，区间外原样保留。" +
        "点「添加片段」新建一段，默认 5 秒、参数为 0（不变调），点片段行改时间和半音数。" +
        "多个片段可以前后相接，但重叠的部分只会按先添加的那段处理一次。" +
        "移调用 Signalsmith，音高变了但时长不变，所以片段总长度不会因为变调而改变。"

    "segment_gain" -> "分段修改音量只对片段区间内的音频加增益，区间外原样保留。" +
        "点「添加片段」新建一段，默认 5 秒、0dB（等于不处理），点片段行改时间和增益。" +
        "正数放大、负数衰减，单段超过 0dB 容易削波失真。"

    "convert" -> "格式转换可以改输出格式、采样率、比特率和声道。" +
        "支持 mp3 / wav / flac / aac / m4a：mp3 走 LAME 固定码率，aac 和 m4a 是同一个编码器" +
        "（m4a 多一层 MPEG-4 容器），flac 和 wav 是无损，wav 不压缩所以体积最大。" +
        "无损格式没有比特率可调，界面上会置灰；无损格式也不写标签，封面和歌词会丢。" +
        "重采样和编码都在导出时做，所以「试听」听到的还是原始参数，保存后的成品才生效。"

    "denoise" -> "两种降噪方式：通用是频域门限，把起始频率以下和结束频率以上滤掉，" +
        "预设就是常用带宽（全频/宽频适合音乐，人声/语音适合录音，电话最窄）。" +
        "录音降噪用 RNNoise（Xiph 官方，Firefox 和 WebRTC 同款神经网络算法），" +
        "针对平稳背景噪声（风扇、电流声）效果最好，它不看频率参数。" +
        "模式只改处理力度：稳定轻一些，正常按标准力度。" +
        "降噪可能轻微影响原始声音细节，建议先试听。"

    "speed_pitch" -> "变速变调用的是 Signalsmith Stretch（BBC R&D 在 ADC22 发表的算法，MIT 许可），" +
        "变速和变调同时完成、互不影响，并且会尽量保住音色。" +
        "音调和速度都用百分比：100% 是原调 / 原速，一个半音约等于 ±5.9%，不是 ±8%。" +
        "速度和时间是反比关系：速度 200% 出来的一半长。" +
        "目前只有这一种内核，没有「新旧内核」切换。"

    "loudness" -> "响度标准化按 EBU R128 / ITU BS.1770 标准测量整体响度（LUFS）并调整到目标值。" +
        "这是 Spotify、YouTube 用的标准，比单纯把峰值顶满更接近听感一致。" +
        "默认 -14 LUFS 是流媒体常用值。"

    else -> "处理完成后导出为 MP3。"
}
